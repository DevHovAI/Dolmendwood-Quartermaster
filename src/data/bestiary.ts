/**
 * What the books say about a creature, from wherever they say it.
 *
 * The bestiary keys by page and the appendices by name, so the caller hands
 * over both and gets whichever exists.
 */
export function creatureEntry(
  name: string | undefined,
  page: number | undefined
): BestiaryEntry | undefined {
  return (page ? BESTIARY[page] : undefined) ?? (name ? APPENDIX[name] : undefined);
}

export function bestiaryPage(page: number | undefined): BestiaryEntry | undefined {
  return page ? BESTIARY[page] : undefined;
}

/**
 * What the bestiary says about a creature, beyond its page and its lair chance.
 *
 * The Monster Book gives every entry more than statistics: a d6 of **traits** to
 * pick one out of a group, a d4 of **encounters** — whole situations the
 * creature might be found in — a d4 of **lairs**, and a line each of behaviour,
 * speech, morale and hoard. All of it is the answer to "and what is it actually
 * doing?", which is the question a rolled name leaves behind, and all of it
 * costs a page-turn in the middle of play.
 *
 * **Keyed by Monster Book page, not by name.** The page is already known for
 * every creature the encounter tables can produce (see `MONSTERS` in
 * `encounters.ts`), the bestiary runs one creature per page, and a number
 * cannot be spelt two ways. The comment above each entry names it for a reader.
 *
 * Only the seventy-seven entries with a stat block are here. Animals, everyday
 * mortals and adventurers have compact blocks with none of this, and the four
 * beings that live in the Campaign Book are not in this book at all.
 *
 * Nothing descriptive is copied: no illustrations, no read-aloud text, none of
 * the prose about what a creature is. These are the tables a Referee rolls on.
 */
export interface BestiaryEntry {
  /** The creature's Level, which is what an OSE table reads as its Hit Dice. */
  level?: number;
  /** Armour Class, as the stat block prints it. */
  ac?: number;
  /**
   * Hit Points as the book writes them — the dice, "4d8". Kept as the string
   * rather than a pair of numbers, because one entry (the talking animal) prints
   * "By species" instead, and because the string is what gets rolled.
   */
  hp?: string;
  /** The average the book prints in brackets after the dice. Absent where the dice are. */
  hpAverage?: number;
  /**
   * Three lines saying what this is, in plain words.
   *
   * **Written for this module, not copied from the book.** The books' own
   * descriptions are Necrotic Gnome's prose and stay in the reader's own copy;
   * what a creature looks like and what it wants are facts, and these are those
   * facts said again in ordinary English. Where the exact wording matters, the
   * page reference on the card opens the book itself.
   */
  flavour?: string[];
  /** Size, type, intelligence and Alignment, as the book prints them on one line. */
  kind?: string;
  morale?: number;
  behaviour?: string;
  speech?: string;
  /** The treasure code for what is kept in the lair, absent when it keeps none. */
  hoard?: string;
  /** d6 — one detail that tells this individual from the rest of its kind. */
  traits?: string[];
  /** d4 (once d6) — a situation to find it in, rather than a bare sighting. */
  encounters?: string[];
  /** d4 — what its lair looks like, for the encounters that happen at home. */
  lairs?: string[];
  /**
   * d6 — example names, for the creatures that use them.
   *
   * Thirty-two entries print a list. Another twenty-one point at a naming
   * section in one of the other two books instead, and those are kept as
   * `namesNote` so the card can say where to look rather than going quiet.
   */
  names?: string[];
  namesNote?: string;
  /**
   * The naming table in one of the other books that `namesNote` points at,
   * where the pointer could be followed. See `nameTables.ts`.
   */
  nameTable?: string;
}

